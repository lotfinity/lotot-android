const DICTIONARIES = { en: EN, fr: FR };

export function normalizeLanguage(value) {
  const normalized = String(value || '').trim().toLowerCase();
  return normalized === 'fr' || normalized.startsWith('fr-') ? 'fr' : 'en';
}

let activeLanguage = normalizeLanguage(
  window.LotoTNative?.getAppLanguage?.() || document.documentElement.lang || navigator.language,
);

export function setLanguage(value) {
  activeLanguage = normalizeLanguage(value);
  document.documentElement.lang = activeLanguage;
  return activeLanguage;
}

export function getLanguage() {
  return activeLanguage;
}

export function t(key, values = {}, fallback = '') {
  const dictionary = DICTIONARIES[activeLanguage] || EN;
  let text = dictionary[key] ?? EN[key] ?? fallback ?? key;
  if (text === null || text === undefined) return '';
  return String(text).replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) => (
    values[name] === null || values[name] === undefined ? '' : String(values[name])
  ));
}
